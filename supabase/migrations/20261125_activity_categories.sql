-- 3) Wyszukiwanie z filtrem kategorii ---------------------------------------------
-- Zmiana parametrów i wyniku wymaga drop + create (inaczej powstałby drugi wariant
-- funkcji, którego PostgREST nie umiałby rozróżnić).
drop function if exists public.search_classes_nearby(
  double precision, double precision, integer, integer, class_level, class_format);

create function public.search_classes_nearby(
  lat double precision,
  lng double precision,
  radius_m integer default 5000,
  p_activity_type_id integer default null,
  p_level class_level default null,
  p_format class_format default null,
  p_category_id integer default null
)
returns table(
  class_id uuid, title text, activity text, category text,
  level class_level, format class_format, price_pln numeric, schedule_note text,
  place_id uuid, place_name text, address text,
  place_lat double precision, place_lng double precision, distance_m double precision
)
language sql
stable
set search_path to 'public', 'extensions'
as $$
  select
    c.id, c.title, a.name, k.name, c.level, c.format, c.price_pln, c.schedule_note,
    p.id, p.name, p.address,
    st_y(p.location::geometry), st_x(p.location::geometry),
    st_distance(p.location, st_point(lng, lat)::geography)
  from classes c
  join places p on p.id = c.place_id
  join activity_types a on a.id = c.activity_type_id
  join activity_categories k on k.id = a.category_id
  where c.is_active
    and st_dwithin(p.location, st_point(lng, lat)::geography, radius_m)
    and (p_category_id is null or a.category_id = p_category_id)
    and (p_activity_type_id is null or c.activity_type_id = p_activity_type_id)
    and (p_level  is null or c.level  = p_level)
    and (p_format is null or c.format = p_format)
  order by 14;
$$;

grant execute on function public.search_classes_nearby(
  double precision, double precision, integer, integer, class_level, class_format, integer
) to anon, authenticated;

